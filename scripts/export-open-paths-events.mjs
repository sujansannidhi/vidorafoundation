#!/usr/bin/env node
/**
 * Generates ops/open-paths/EventsData.gs from src/content/volunteer.ts, so the
 * Apps Script backend and the website share one definition of every event,
 * credit, cap, status and ID format.
 *
 *   npm run export:events
 *
 * Rerun after any change to the events in volunteer.ts, then push the Apps
 * Script project again.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const vol = await import(new URL('../src/content/volunteer.ts', import.meta.url));

const EVENTS = vol.events.map((e) => ({
  id: e.id,
  slug: e.slug,
  name: e.name,
  mode: e.mode,
  partnerRequired: e.partnerRequired,
  credit: e.credit,
  capRule: e.capRule,
  cap: e.cap,
  steps: e.steps,
  proof: e.proof,
  safety: e.safety,
  active: true,
}));

const CAPS = {
  hoursPerMonth: vol.openPaths.caps.hoursPerMonth,
  hoursPerSchoolYear: vol.openPaths.caps.hoursPerSchoolYear,
  schoolYear: vol.openPaths.caps.schoolYear,
  schoolYearStartMonth: 8,
  maxHoursPerSubmission: 8,
};

const STATUSES = {
  volunteer: [...vol.VOLUNTEER_STATUS],
  submission: [...vol.SUBMISSION_STATUS],
  certificate: [...vol.CERTIFICATE_STATUS],
};

const COPY = {
  counselorNote: vol.openPaths.counselorNote,
  letterStatusLine: vol.letterStatusLine,
  letterContents: vol.letterContents,
  originality: vol.openPaths.originality,
  timeline: vol.openPaths.timeline,
  pvsaShort: 'Vidora is not a President’s Volunteer Service Award certifying organization.',
};

const out = `// GENERATED by scripts/export-open-paths-events.mjs from src/content/volunteer.ts.
// Do not edit by hand. Change volunteer.ts, run \`npm run export:events\`, and push again.

const EVENTS = ${JSON.stringify(EVENTS, null, 2)};

const CAPS = ${JSON.stringify(CAPS, null, 2)};

const STATUSES = ${JSON.stringify(STATUSES, null, 2)};

const ID_FORMATS = ${JSON.stringify(vol.ID_FORMATS, null, 2)};

const CERTIFICATE_SUFFIX_ALPHABET = ${JSON.stringify(vol.CERTIFICATE_SUFFIX_ALPHABET)};

const CERTIFICATE_ID_PATTERN = ${vol.CERTIFICATE_ID_PATTERN.toString()};

const SITE_COPY = ${JSON.stringify(COPY, null, 2)};
`;

const target = fileURLToPath(new URL('../ops/open-paths/EventsData.gs', import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${EVENTS.length} events to ops/open-paths/EventsData.gs`);
